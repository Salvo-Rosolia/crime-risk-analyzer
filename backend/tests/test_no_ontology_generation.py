"""Tests for the ablation arm «LLM without ontological contribution» (#236).

The arm exists to isolate ONE variable: the contribution of the ontology in the
PROMPT. Everything else — model, temperature, POI snapshot, structure of the
response asked of the model and legal constraints — must stay identical to the
full arm, otherwise the comparison measures two things at once and says nothing
about C3. The tests here lock down exactly that symmetry: what stays the same
(structure, legal rules, POI lines) and what is removed (hazards,
vulnerabilities, citations, controlled vocabulary).

Offline: the LLM client is an async double, no network.
"""

