class _FakeLLMClient:
    """Async double of the client: records ``(system, user)`` of every call."""

    def __init__(self, response: LLMResponse) -> None:
        self._response = response
        self.calls: list[tuple[str, str]] = []

    async def generate(self, system_prompt: str, user_content: str) -> LLMResponse:
        self.calls.append((system_prompt, user_content))
        return self._response


def _llm_response(**overrides: Any) -> LLMResponse:
    base: dict[str, Any] = {
        "text": (f"Sintesi.\n\n{LLM_SYNTHESIS_BLOCK_HEADER}\nColosseo: borseggio."),
        "llm_used": GROQ_MODEL,
        "tokens_input": 300,
        "tokens_output": 200,
        "cache_hit": False,
        "temperature": 0.0,
        "seed": 0,
        "prompt_hash": "hash-del-prompt-nudo",
    }
    base.update(overrides)
    return LLMResponse(**base)


